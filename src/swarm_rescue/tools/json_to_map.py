def _module_name(name: str) -> str:
    normalized = re.sub(r"[^0-9a-zA-Z]+", "_", name.strip()).strip("_").lower()
    if not normalized:
        raise ValueError("name must contain at least one alphanumeric character")
    if normalized[0].isdigit():
        normalized = f"{normalized}"
    return normalized


def _class_name(module_name: str) -> str:
    return "Map" + "".join(part.capitalize() for part in module_name.split("_") if part)


def _point_to_world(x: int, y: int, width: int, height: int) -> Tuple[int, int]:
    xw = int(round(x - width / 2))
    yw = int(round(-y + height / 2))
    return xw, yw


def _rect_to_world(
    top_left: Tuple[int, int],
    bottom_right: Tuple[int, int],
    width: int,
    height: int,
) -> Tuple[Tuple[int, int], int, int]:
    x0, y0 = top_left
    x1, y1 = bottom_right
    up_left = _point_to_world(x0, y0, width, height)
    return up_left, int(round(x1 - x0)), int(round(y1 - y0))


def _editor_rect_to_center_size_world(
    element: WallElement,
    width: int,
    height: int,
) -> Tuple[int, int, int, int]:
    """
    Map editor pixel rectangle -> (size_w, size_h, center_x_world, center_y_world).

    Sizes match pixel span (same convention as hand-written maps).
    """
    if element.top_left is None or element.bottom_right is None:
        raise ValueError("element must have top_left and bottom_right")
    x0, y0 = element.top_left
    x1, y1 = element.bottom_right
    size_w = max(1, int(round(x1 - x0)))
    size_h = max(1, int(round(y1 - y0)))
    cx_px = (x0 + x1) * 0.5
    cy_px = (y0 + y1) * 0.5
    cx_w, cy_w = _point_to_world(int(round(cx_px)), int(round(cy_px)), width, height)
    return size_w, size_h, cx_w, cy_w


def _write_walls_file(path: Path, width: int, height: int, elements: List[WallElement]) -> None:
    boxes = [element for element in elements if element.element_type == RECT_WALL]
    walls = [element for element in elements if element.element_type == LINE_WALL]

    lines = [
        '"""',
        "This file was generated by the tool 'json_to_map.py' in the directory tools.",
        '"""',
        "from swarm_rescue.simulation.elements.normal_wall import NormalWall, NormalBox",
        "",
        "",
        f"# Dimension of the map : ({width}, {height})",
        "def add_boxes(playground):",
    ]

    if boxes:
        for i, element in enumerate(boxes):
            if element.top_left is None or element.bottom_right is None:
                continue
            up_left, box_width, box_height = _rect_to_world(element.top_left, element.bottom_right, width, height)
            lines.extend(
                [
                    f"    # box {i}",
                    f"    box = NormalBox(up_left_point=({up_left[0]}, {up_left[1]}),",
                    f"                    width={box_width}, height={box_height})",
                    "    playground.add(box, box.wall_coordinates)",
                    "",
                ]
            )
    else:
        lines.extend(["    pass", ""])

    lines.extend(["", "def add_walls(playground):"])
    if walls:
        for i, element in enumerate(walls):
            if element.points is None:
                continue
            start = _point_to_world(element.points[0][0], element.points[0][1], width, height)
            end = _point_to_world(element.points[1][0], element.points[1][1], width, height)
            lines.extend(
                [
                    f"    # wall {i}",
                    f"    wall = NormalWall(pos_start=({start[0]}, {start[1]}),",
                    f"                      pos_end=({end[0]}, {end[1]}))",
                    "    playground.add(wall, wall.wall_coordinates)",
                    "",
                ]
            )
    else:
        lines.extend(["    pass", ""])

    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


