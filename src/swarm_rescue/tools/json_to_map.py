def generate_map_from_json(
    *,
    input_json_path: Union[str, Path],
    name: str,
    maps_dir: Union[str, Path] = "src/swarm_rescue/maps",
) -> Dict[str, str]:
    input_json_path = Path(input_json_path)
    maps_dir = Path(maps_dir)
    module_name = _module_name(name)

    with input_json_path.open("r", encoding="utf-8") as f:
        data = json.load(f)

    canvas = data.get("canvas", {}) or {}
    width = int(canvas.get("width", 1113))
    height = int(canvas.get("height", 750))
    elements = load_elements(data, width=width, height=height)

    maps_dir.mkdir(parents=True, exist_ok=True)

    map_py = maps_dir / f"map_{module_name}.py"
    walls_py = maps_dir / f"walls_{module_name}.py"

    _write_walls_file(walls_py, width, height, elements)

    start_area_el: Optional[WallElement] = None
    disposal_center_el: Optional[WallElement] = None
    for element in reversed(elements):
        if element.element_type == START_AREA and start_area_el is None:
            start_area_el = element
        if element.element_type == DISPOSAL_CENTER and disposal_center_el is None:
            disposal_center_el = element
        if start_area_el is not None and disposal_center_el is not None:
            break

    # 起点区域：只需要中心点坐标（世界坐标），不需要尺寸和 ReturnArea 对象
    start_area_center = None
    if start_area_el is not None and start_area_el.top_left and start_area_el.bottom_right:
        cx_px = (start_area_el.top_left[0] + start_area_el.bottom_right[0]) * 0.5
        cy_px = (start_area_el.top_left[1] + start_area_el.bottom_right[1]) * 0.5
        start_area_center = _point_to_world(int(round(cx_px)), int(round(cy_px)), width, height)

    disposal_center_placement = (
        _editor_rect_to_center_size_world(disposal_center_el, width, height) if disposal_center_el else None
    )

    _write_map_file(
        map_py,
        module_name,
        width,
        height,
        start_area_center=start_area_center,
        disposal_center_placement=disposal_center_placement,
    )

    return {
        "map_py": str(map_py),
        "walls_py": str(walls_py),
    }


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate Swarm-Rescue map files from map editor JSON.")
    parser.add_argument("input_json", help="Path to map editor JSON")
    parser.add_argument("--name", required=True, help="Map name, e.g. custom_example")
    parser.add_argument("--maps-dir", default="src/swarm_rescue/maps", help="Directory for generated map Python files")
    return parser.parse_args()


def main() -> None:
    args = _parse_args()
    paths = generate_map_from_json(
        input_json_path=args.input_json,
        name=args.name,
        maps_dir=args.maps_dir,
    )
    print(json.dumps(paths, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
